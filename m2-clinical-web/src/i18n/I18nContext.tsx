interface Ctx { locale: Locale; setLocale: (x: Locale) => void; t: (key: string, vars?: Record<string, string | number>) => string }
const I18nContext = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    try { return (localStorage.getItem('m2_locale') as Locale) || 'zh-CN' } catch { return 'zh-CN' }
  })

  useEffect(() => {
    setRuntimeLocale(locale)
    document.title = dict[locale].pageTitle
  }, [locale])

  const value = useMemo(() => ({
    locale,
    setLocale: (x: Locale) => { setLocale(x); try { localStorage.setItem('m2_locale', x) } catch { /* ignore */ } },
    t: (key: string, vars?: Record<string, string | number>) => {
      const raw = dict[locale][key] ?? dict['zh-CN'][key] ?? key
      if (!vars) return raw
      return Object.entries(vars).reduce(
        (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
        raw,
      )
    },
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}
